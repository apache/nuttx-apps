/* Corresponds to PKCS12_load() in pkcs12_api_test.c.
 * We load from embedded DER data instead of file.
 */

static PKCS12 *pkcs12_load(void)
{
  const unsigned char *p = g_test_p12_data;

  return d2i_PKCS12(NULL, &p, (long)g_test_p12_data_len);
}

/* OPENSSL_sk_free() only drops the stack container; this wrapper has no
 * pop_free, so release each X509 entry first, as PKCS12_newpass() does.
 */

static void free_x509_sk(STACK_OF(X509) *sk)
{
  int i;

  if (sk == NULL)
    {
      return;
    }

  for (i = 0; i < sk->num; i++)
    {
      X509_free((X509 *)sk->data[i]);
    }

  OPENSSL_sk_free(sk);
}

/* Corresponds to changepass() in pkcs12_api_test.c.
 * Uses BIO roundtrip matching OpenSSL original flow:
 * PKCS12_newpass → i2d_PKCS12_bio(mem) → d2i_PKCS12_bio(mem) →
 * parse with new password → compare key and cert.
 */

static int changepass(PKCS12 *p12, EVP_PKEY *key, X509 *cert,
                      STACK_OF(X509) *ca)
{
  STACK_OF(X509) *ca2 = NULL;
  EVP_PKEY *key2 = NULL;
  PKCS12 *p12new = NULL;
  X509 *cert2 = NULL;
  BIO *bio = NULL;
  int ret = 0;

  if (PKCS12_newpass(p12, TEST_P12_PASSWORD, "NEWPASS") != 1)
    {
      printf("[CP] FAIL: newpass\n");
      goto err;
    }

  bio = BIO_new(BIO_s_mem());
  if (bio == NULL)
    {
      printf("[CP] FAIL: BIO_new\n");
      goto err;
    }

  if (i2d_PKCS12_bio(bio, p12) != 1)
    {
      printf("[CP] FAIL: i2d_PKCS12_bio\n");
      goto err;
    }

  p12new = d2i_PKCS12_bio(bio, NULL);
  if (p12new == NULL)
    {
      printf("[CP] FAIL: d2i_PKCS12_bio\n");
      goto err;
    }

  if (PKCS12_parse(p12new, "NEWPASS", &key2, &cert2, &ca2) != 1)
    {
      printf("[CP] FAIL: re-parse\n");
      goto err;
    }

  if (key != NULL)
    {
      if (key2 == NULL || EVP_PKEY_eq(key, key2) != 1)
        {
          printf("[CP] FAIL: key_eq (key2=%p)\n", key2);
          goto err;
        }
    }

  if (cert != NULL)
    {
      if (cert2 == NULL || X509_cmp(cert, cert2) != 0)
        {
          printf("[CP] FAIL: cert_cmp (cert2=%p)\n", cert2);
          goto err;
        }
    }

  ret = 1;

err:
  BIO_free(bio);
  PKCS12_free(p12new);
  EVP_PKEY_free(key2);
  X509_free(cert2);
  free_x509_sk(ca2);
  return ret;
}

/****************************************************************************
 * Name: test_null_args
 *
 * Description:
 *   Ported from pkcs12_api_test.c test_null_args().
 *   PKCS12_parse(NULL, NULL, NULL, NULL, NULL) must return 0 (failure).
 ****************************************************************************/

static void test_null_args(void **state)
{
  assert_int_equal(PKCS12_parse(NULL, NULL, NULL, NULL, NULL), 0);
}

/****************************************************************************
 * Name: test_pkcs12_parse
 *
 * Description:
 *   Ported from pkcs12_api_test.c pkcs12_parse_test().
 *   Load a valid P12 → parse → verify key, cert, ca are present →
 *   then run changepass round-trip.
 ****************************************************************************/

static void test_pkcs12_parse(void **state)
{
  STACK_OF(X509) *ca = NULL;
  PKCS12 *p12 = NULL;
  EVP_PKEY *key = NULL;
  X509 *cert = NULL;

  p12 = pkcs12_load();
  assert_non_null(p12);

  assert_int_equal(PKCS12_parse(p12, TEST_P12_PASSWORD,
                                &key, &cert, &ca), 1);

  /* Our test data has key, cert, and ca */

  assert_non_null(key);
  assert_non_null(cert);
  assert_non_null(ca);

  /* changepass round-trip: newpass → serialize → parse → compare */

  assert_int_equal(changepass(p12, key, cert, ca), 1);

  PKCS12_free(p12);
  EVP_PKEY_free(key);
  X509_free(cert);
  free_x509_sk(ca);
}

