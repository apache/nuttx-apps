"""Generate <zephyr/syscalls/*.h> for a build without CONFIG_USERSPACE.

Upstream headers declare system calls as "__syscall T f(args);" and include
a generated <zephyr/syscalls/NAME.h> that defines f() to call z_impl_f().
zblue runs in a single address space with no system call layer, so each
generated wrapper is just that call; the port implements z_impl_f().
"""

import os
import re
import sys

PROTO = re.compile(r"__syscall\s+([^;{]*?)\b(\w+)\s*\(([^;{]*?)\)\s*;", re.S)
INCLUDE = re.compile(r"#\s*include\s*<zephyr/syscalls/(\w+)\.h>")


def arg_name(arg):
    arg = arg.strip()
    m = re.search(r"\(\s*\*\s*(\w+)\s*\)", arg)
    if m:
        return m.group(1)
    m = re.search(r"(\w+)\s*(\[[^\]]*\])?$", arg)
    return m.group(1)


def split_args(args):
    out, depth, cur = [], 0, ""
    for c in args:
        if c == "," and depth == 0:
            out.append(cur)
            cur = ""
            continue
        depth += c == "("
        depth -= c == ")"
        cur += c
    if cur.strip():
        out.append(cur)
    return out


def wrapper(ret, name, args):
    ret = " ".join(ret.split())
    args = " ".join(args.split())
    params = [] if args in ("", "void") else split_args(args)
    call = ", ".join(arg_name(a) for a in params)
    body = "" if ret == "void" else "return "
    return (
        "extern %s z_impl_%s(%s);\n"
        "static inline %s %s(%s)\n{\n\t%sz_impl_%s(%s);\n}\n\n"
        % (ret, name, args or "void", ret, name, args or "void", body, name, call)
    )


def main():
    incdir, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)
    for root, _, files in os.walk(incdir):
        for fn in files:
            if not fn.endswith(".h"):
                continue
            text = open(os.path.join(root, fn), errors="ignore").read()
            m = INCLUDE.search(text)
            if not m:
                continue
            nocomment = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
            guard = "Z_ZBLUE_SYSCALLS_%s_H" % m.group(1).upper()
            out = [
                "/* Generated by tools/gen_syscalls.py, do not edit */\n",
                "#ifndef %s\n#define %s\n\n" % (guard, guard),
                '#ifdef __cplusplus\nextern "C" {\n#endif\n\n',
            ]
            for p in PROTO.finditer(nocomment):
                out.append(wrapper(*p.groups()))
            out.append("#ifdef __cplusplus\n}\n#endif\n\n#endif\n")
            path = os.path.join(outdir, m.group(1) + ".h")
            new = "".join(out)
            if not os.path.exists(path) or open(path).read() != new:
                with open(path, "w") as f:
                    f.write(new)


if __name__ == "__main__":
    main()
